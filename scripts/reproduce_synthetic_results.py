#!/usr/bin/env python3
"""Reproduce the synthetic inference results from the released checkpoints.

This script does NOT train anything. It loads weights that already exist
and runs a forward pass. There is no optimizer, no gradient, no training
loop, and no new checkpoint is produced.

    INPUTS                                        OUTPUT
    checkpoints/synthetic/<model>_snr<N>_seed<S>.pt  ─┐
    data/synthetic/synthetic_IVIM_test_2D.h5         ─┴─▶ results/
                                                          synthetic_regenerated/
                                                          <model>_snr<N>/
                                                          inferred_seed<S>.h5

The snr and seed in a checkpoint filename describe the conditions it was
trained under previously. They are read from the manifest to choose which
file to open; this script does not vary them and cannot change them.

Why it exists
-------------
scripts/make_manuscript_figures.py reads results/synthetic, a set of
inference outputs committed to the repository. Without this script a reader
would have to take those outputs on trust: they would hold the weights and
the test data, but no way to get from one to the other. Running it closes
that gap.

With --compare it goes further and checks the regenerated outputs against
the committed reference, which tests whether the released checkpoints
really do reproduce the published numbers.

Output goes to results/synthetic_regenerated by default, never to
results/synthetic, so the committed reference cannot be overwritten.

On reproducibility
------------------
Rician noise is injected during the forward pass, seeded with
torch.manual_seed. The random stream depends on the backend, so a run on
Metal or CPU will not reproduce a CUDA run voxel for voxel: different
voxels survive the signal cleaning step and different noise reaches the
network. Summary statistics agree closely, individual voxels do not.
--compare reports the difference in those terms rather than asserting
equality.

Training, for contrast, lives in pace/learn_ivim.py. That is the module
that builds a network from scratch and writes a checkpoint.

Usage
-----
    python scripts/reproduce_synthetic_results.py --models pace --snrs 25 --seeds 19
    python scripts/reproduce_synthetic_results.py
    python scripts/reproduce_synthetic_results.py --compare
    python scripts/reproduce_synthetic_results.py --device cpu
"""

from __future__ import annotations

import argparse
import sys
import time
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from pace import common as C

# Written by the analysis writer that produced the committed results.
PRED_KEYS = ["Dpar_pred", "Fint_pred", "Dint_pred", "Fmv_pred", "Dmv_pred",
             "S0_pred"]


class InMemoryIVIMDataset:
    """IVIMDataset equivalent that reads the H5 once instead of per voxel.

    IVIMDataset.__getitem__ indexes the open HDF5 file five times for every
    voxel, so a 38,000 voxel pass performs 190,000 reads against gzip
    compressed datasets. Loading each array once and slicing it in memory
    gives identical values roughly two orders of magnitude faster. The
    synthetic test file is about 11 MB uncompressed.

    The per voxel transform is copied from IVIMDataset so the two produce
    the same tensors: z-scoring is applied to each structural channel and
    to the b0 patch, and the zeroed placeholders keep their exact shapes
    when a modality is switched off.
    """

    def __init__(self, h5_path, use_struct=True, use_b0=True):
        import h5py
        from pace.deep_models import zscore_patch_np

        self._zscore = zscore_patch_np
        self.use_struct, self.use_b0 = use_struct, use_b0

        with h5py.File(h5_path, "r") as f:
            self.X = f["IVIM_cube"][:].astype(np.float32)
            self.SP = f["Struct_patch"][:].astype(np.float32)
            self.B0 = f["B0_patch"][:].astype(np.float32)
            self.T = f["Tissue"][:]
            self.L = f["Lesion"][:]

        self.nbvals = self.X.shape[-1]
        self._zero_sp = np.zeros((2, 3, 3), dtype=np.float32)
        self._zero_b0 = np.zeros((1, 3, 3), dtype=np.float32)

    def __len__(self):
        return len(self.X)

    def __getitem__(self, idx):
        import torch

        if self.use_struct:
            sp = self.SP[idx].copy()
            sp[0] = self._zscore(sp[0])
            sp[1] = self._zscore(sp[1])
        else:
            sp = self._zero_sp

        if self.use_b0:
            b0 = self.B0[idx].copy()
            b0[0] = self._zscore(b0[0])
        else:
            b0 = self._zero_b0

        return {
            "x_true": torch.from_numpy(self.X[idx]),
            "struct_patch": torch.from_numpy(sp),
            "b0_patch": torch.from_numpy(b0),
            "tissue": torch.tensor(int(self.T[idx]), dtype=torch.int16),
            "lesion": torch.tensor(int(self.L[idx]), dtype=torch.int16),
        }

    def close(self):
        pass


def _tissue_key(model):
    return "Tissue"


def run_one(ck, paths, device, batch_size, out_root, overwrite, quiet=False):
    """Run one checkpoint over the test set and write an H5. Returns a dict."""
    import h5py
    import torch
    from torch.utils.data import DataLoader
    from pace.deep_models import clean_ivim_signals

    out_dir = out_root / f"{ck.model}_snr{ck.snr_db}"
    out_path = out_dir / f"inferred_seed{ck.seed}.h5"
    if out_path.is_file() and not overwrite:
        if not quiet:
            print(f"  [skip] exists: {out_path.name}")
        return None

    cfg = C.ARCH_CONFIGS[ck.cfg_name]
    bvals = C.load_bvals(paths)
    dev = C.resolve_device(device)

    net, _ = C.load_net(ck.model, ck.snr_db, ck.seed, bvals=bvals,
                        device=device, paths=paths, strict=True)

    ds = InMemoryIVIMDataset(str(paths.synthetic_test),
                             use_struct=cfg["use_struct"],
                             use_b0=cfg["use_b0"])
    loader = DataLoader(ds, batch_size=batch_size, shuffle=False,
                        num_workers=0, drop_last=False)
    n_batches = len(loader)
    if not quiet:
        print(f"  {len(ds):,} voxels in {n_batches} batches on {dev}",
              flush=True)

    preds = {k: [] for k in PRED_KEYS}
    tissue, lesion, valid_chunks = [], [], []

    # The noise is part of the experiment, so the seed matches the training
    # seed of this checkpoint, exactly as the analysis did.
    torch.manual_seed(ck.seed)

    t0 = time.time()
    with torch.no_grad():
        for bi, batch in enumerate(loader):
            # The first batch on Metal includes a kernel compile, so it can
            # take far longer than the rest. Report it separately rather than
            # letting the run look stalled.
            if not quiet and (bi == 0 or (bi + 1) % 10 == 0
                              or bi + 1 == n_batches):
                done_frac = (bi + 1) / n_batches
                el = time.time() - t0
                eta = el / max(done_frac, 1e-9) - el
                print(f"\r    batch {bi + 1}/{n_batches}  "
                      f"{el:5.1f}s elapsed, {eta:5.1f}s remaining",
                      end="", flush=True)
            SP_in = (batch["struct_patch"].to(dev)
                     if cfg["spatial_on"] and cfg["use_struct"] else None)
            B0_in = (batch["b0_patch"].to(dev)
                     if cfg["spatial_on"] and cfg["use_b0"] else None)

            X, SP_clean, B0_clean, vm = clean_ivim_signals(
                batch["x_true"].to(dev), SP_in, B0_in, bvals,
                inject_noise=True, noise_type="rician",
                noise_level=float(ck.snr_db),
            )
            SP = SP_clean if cfg["spatial_on"] else None
            B0 = B0_clean if cfg["spatial_on"] else None

            vm_np = vm.cpu().numpy().astype(bool)
            valid_chunks.append(vm_np)
            if X.shape[0] < 1:
                continue

            out = net(ivim_true_signal=X, structural_patch=SP, b0_patch=B0)
            Dpar, Fint, Dint, Fmv, Dmv, S0 = out["ivim_params"]

            preds["Dpar_pred"].append(Dpar.cpu().numpy().ravel())
            preds["Fmv_pred"].append(Fmv.cpu().numpy().ravel())
            preds["Dmv_pred"].append(Dmv.cpu().numpy().ravel())
            preds["S0_pred"].append(S0.cpu().numpy().ravel())
            if Fint is not None:
                preds["Fint_pred"].append(Fint.cpu().numpy().ravel())
            if Dint is not None:
                preds["Dint_pred"].append(Dint.cpu().numpy().ravel())

            tissue.append(batch["tissue"].numpy()[vm_np])
            lesion.append(batch["lesion"].numpy()[vm_np])

    ds.close()
    elapsed = time.time() - t0
    if not quiet:
        print(flush=True)

    global_valid = np.concatenate(valid_chunks)
    save = {k: np.concatenate(v) for k, v in preds.items() if v}
    save["Tissue"] = np.concatenate(tissue)
    save["Lesion"] = np.concatenate(lesion)
    save["Valid_mask"] = global_valid.astype(np.uint8)
    save["bvals"] = np.asarray(bvals, dtype=np.float32)

    n_kept = len(save["Dpar_pred"])
    n_total = len(global_valid)

    lengths = {len(v) for k, v in save.items() if k not in ("bvals",)}
    lengths.discard(n_total)  # Valid_mask is full length by design
    if len(lengths) > 1:
        raise ValueError(f"{ck.public_name}: inconsistent array lengths "
                         f"{sorted(lengths)}")

    out_dir.mkdir(parents=True, exist_ok=True)
    with h5py.File(out_path, "w") as f:
        for k, v in save.items():
            f.create_dataset(k, data=v, compression="gzip")

    if not quiet:
        print(f"  {n_kept:,}/{n_total:,} voxels kept "
              f"({100 * n_kept / max(n_total, 1):.1f}%)  "
              f"{elapsed:.1f}s  -> {out_path.name}")

    del net
    return {"public_name": ck.public_name, "n_kept": n_kept,
            "n_total": n_total, "seconds": elapsed, "path": out_path}


def compare(ck, paths, out_root):
    """Compare a regenerated result against the committed reference.

    Reports distribution level agreement. Voxel level equality is not
    expected: the noise stream differs by backend, so the two runs do not
    even retain the same set of voxels.
    """
    import h5py

    ref_path = (paths.results_dir / f"{ck.model}_snr{ck.snr_db}"
                / f"inferred_seed{ck.seed}.h5")
    new_path = (out_root / f"{ck.model}_snr{ck.snr_db}"
                / f"inferred_seed{ck.seed}.h5")
    if not (ref_path.is_file() and new_path.is_file()):
        return None

    rows = []
    with h5py.File(ref_path) as fr, h5py.File(new_path) as fn:
        for key in PRED_KEYS:
            if key not in fr or key not in fn:
                continue
            a = fr[key][:].astype(np.float64)
            b = fn[key][:].astype(np.float64)
            a, b = a[np.isfinite(a)], b[np.isfinite(b)]
            if a.size == 0 or b.size == 0:
                continue
            ma, mb = a.mean(), b.mean()
            rel = abs(ma - mb) / max(abs(ma), 1e-12)
            rows.append({
                "param": key.replace("_pred", ""),
                "ref_mean": ma, "new_mean": mb, "rel_diff": rel,
                "ref_n": a.size, "new_n": b.size,
            })
    return rows


def main():
    ap = argparse.ArgumentParser(
        description="Reproduce the synthetic inference results from the released checkpoints.")
    ap.add_argument("--models", nargs="+", default=None,
                    help="Neural models to run. Default: all in the manifest.")
    ap.add_argument("--snrs", nargs="+", type=int, default=None)
    ap.add_argument("--seeds", nargs="+", type=int, default=None)
    ap.add_argument("--device", default=None,
                    help="cuda, mps, cpu or auto. Default: auto.")
    ap.add_argument("--batch-size", type=int, default=512)
    ap.add_argument("--out", default="results/synthetic_regenerated",
                    help="Output directory, relative to the repository root.")
    ap.add_argument("--overwrite", action="store_true")
    ap.add_argument("--compare", action="store_true",
                    help="Compare against results/synthetic afterwards.")
    args = ap.parse_args()

    paths = C.load_paths()
    manifest = C.load_manifest(paths)

    out_root = Path(args.out)
    if not out_root.is_absolute():
        out_root = paths.repo_root / out_root

    if out_root.resolve() == paths.results_dir.resolve():
        print("[ERROR] refusing to write into results/synthetic, which holds "
              "the committed reference. Choose another --out.", file=sys.stderr)
        return 2

    todo = [ck for ck in manifest.checkpoints
            if (args.models is None or ck.model in args.models)
            and (args.snrs is None or ck.snr_db in args.snrs)
            and (args.seeds is None or ck.seed in args.seeds)]
    if not todo:
        print("[ERROR] no checkpoints match the selection.", file=sys.stderr)
        print(f"        models {manifest.neural_models}", file=sys.stderr)
        print(f"        SNR    {manifest.snrs()}", file=sys.stderr)
        return 2

    try:
        import torch  # noqa: F401
    except ImportError:
        print("[ERROR] torch is required. pip install torch", file=sys.stderr)
        return 2

    dev = C.resolve_device(args.device)
    print(f"[DATA  ] {paths.synthetic_test.name}")
    print(f"[DEVICE] {dev}")
    print(f"[OUT   ] {out_root.relative_to(paths.repo_root)}")
    print(f"[RUN   ] {len(todo)} checkpoint(s)")
    print()

    done, failed = [], []
    for i, ck in enumerate(todo, 1):
        print(f"[{i}/{len(todo)}] {ck.public_name}  "
              f"cfg={ck.cfg_name} fusion={ck.fusion_mode} "
              f"ordered={ck.use_ordered_diffusion} "
              f"softmax={ck.use_softmax_fractions}")
        try:
            r = run_one(ck, paths, args.device, args.batch_size, out_root,
                        args.overwrite)
            if r:
                done.append(r)
        except Exception as e:
            failed.append((ck.public_name, f"{type(e).__name__}: {e}"))
            print(f"  [FAIL] {type(e).__name__}: {e}")

    print()
    print(f"[DONE] {len(done)} written, {len(failed)} failed")
    for name, err in failed:
        print(f"   {name}: {err}")

    if args.compare:
        print()
        print("=" * 72)
        print(" Regenerated against the committed reference")
        print("=" * 72)
        print(" Voxel level equality is not expected. Rician noise is injected")
        print(" at inference and the random stream depends on the backend, so")
        print(" the two runs retain different voxels and see different noise.")
        print(" Close agreement in the means is the meaningful check.")
        print()
        worst = 0.0
        for ck in todo:
            rows = compare(ck, paths, out_root)
            if not rows:
                continue
            print(f" {ck.public_name}")
            print(f"   {'param':<6} {'reference':>12} {'regenerated':>12} "
                  f"{'rel diff':>10} {'n ref':>8} {'n new':>8}")
            for r in rows:
                worst = max(worst, r["rel_diff"])
                print(f"   {r['param']:<6} {r['ref_mean']:>12.6g} "
                      f"{r['new_mean']:>12.6g} {r['rel_diff']:>9.2%} "
                      f"{r['ref_n']:>8,} {r['new_n']:>8,}")
            print()
        print(f" largest relative difference in any mean: {worst:.2%}")
        print("=" * 72)

    print()
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
